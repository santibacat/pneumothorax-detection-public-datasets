def verify_corrupted_images(filepath):
    """Checks if a single image file is corrupted."""
    try:
        # Attempt to open the image file.
        img = Image.open(filepath)
        # The 'load' method forces loading the image data, catching truncated files.
        img.load()
        return (filepath, False)  # Return tuple: (filepath, is_corrupted)
    except Exception as e:
        # Log the error if an exception occurs (e.g., file not found, format error, truncated)
        logging.warning(f"Corrupted or missing image: {filepath}, Error: {e}")
        return (filepath, True)  # Return tuple: (filepath, is_corrupted)


def find_corrupted_images_parallel(filepaths, max_workers=20):
    """
    Verifies a list of image filepaths in parallel to find corrupted images,
    showing progress based on completion.

    Args:
        filepaths (list): A list of strings, where each string is a path to an image file.
        max_workers (int): The maximum number of threads to use.

    Returns:
        list: A list of filepaths corresponding to corrupted or missing images.
    """
    corrupted_files = []
    # Use ThreadPoolExecutor for I/O-bound tasks like reading files
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        # Submit all tasks and store the future objects
        futures = [
            executor.submit(verify_corrupted_images, fp) for fp in filepaths
        ]

        # Iterate over futures as they complete, using tqdm for progress
        for future in tqdm(
            concurrent.futures.as_completed(futures),
            total=len(filepaths),
            desc="Verifying images",
        ):
            try:
                filepath, is_corrupted = future.result()
                if is_corrupted:
                    corrupted_files.append(filepath)
            except Exception as e:
                # Handle potential exceptions raised within the worker thread itself
                # We need to find which filepath caused this. This is less direct with submit/as_completed.
                # For simplicity, we'll just log a general error here.
                # A more robust solution might involve mapping futures back to filepaths.
                logging.error(f"An error occurred processing a future: {e}")

    return corrupted_files


